/// Родовий відмінок перевода (для omastav): «кімната» → «кімнати».
String ukrGen(String tr) {
  final f = _nounForms[tr];
  return f == null ? tr : '${f.$1} (кого? чого?)';
}

/// Родовий без пояснения; '' — если слова нет в словаре форм.
