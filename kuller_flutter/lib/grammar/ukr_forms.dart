/// Родовой падеж украинского прилагательного мужского рода по правилу
/// (-ий → -ого, -ій → -ього). '' — если это не одиночное прилагательное.
String _adjGen(String tr) {
  if (tr.length < 5 || tr.contains(' ') || tr.contains(',')) return '';
  if (tr[0] != tr[0].toLowerCase()) return '';
  if (tr.endsWith('ий')) return '${tr.substring(0, tr.length - 2)}ого';
  if (tr.endsWith('ій')) return '${tr.substring(0, tr.length - 2)}ього';
  return '';
}

